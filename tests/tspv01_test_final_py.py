import numpy as np
import json
import hmac
import hashlib
import time
import copy
from typing import Dict, Any, Tuple, List, Optional

class TSPv01:
    """TSP v0.1 核心工具類別 — 數學嚴謹 + 工程可驗證"""

    # 預計算所有 27 種 (I, C, O) → S³ 映射 (6 位小數)
    LOOKUP = {}
    for I in [-1, 0, 1]:
        for C in [-1, 0, 1]:
            for O in [-1, 0, 1]:
                v = np.array([1.0, I, C, O], dtype=np.float64)
                v /= np.linalg.norm(v)
                LOOKUP[(I, C, O)] = np.round(v, decimals=6).tolist()

    @staticmethod
    def phi_map(s: Tuple[int, int, int]) -> List[float]:
        """官方 ϕ 映射：(I, C, O) → S³ 單位向量"""
        key = tuple(s)
        if key not in TSPv01.LOOKUP:
            v = np.array([1.0, *s], dtype=np.float64)
            v /= np.linalg.norm(v)
            return np.round(v, decimals=6).tolist()
        return TSPv01.LOOKUP[key].copy()

    @staticmethod
    def chordal_dist(v1: List[float], v2: List[float]) -> float:
        """Chordal Distance on S³: d = ||u - v||₂"""
        return float(np.linalg.norm(np.array(v1) - np.array(v2)))

    @staticmethod
    def canonical_json(data: Dict) -> bytes:
        """RFC 8785 JCS 近似實現（v0.1）"""
        return json.dumps(
            data,
            separators=(',', ':'),
            sort_keys=True,
            ensure_ascii=False
        ).encode('utf-8')

    def verify_packet_integrity(self, packet: Dict,
                                atol: float = 1e-5,
                                unit_norm_tol: float = 1e-4) -> Tuple[bool, str]:
        """驗證封包完整性與幾何一致性"""
        s = packet.get('s')
        vec = packet.get('vec')

        if not isinstance(s, list) or len(s) != 3:
            return False, "s field invalid"
        if not isinstance(vec, list) or len(vec) != 4:
            return False, "vec field invalid"
        if not all(x in [-1, 0, 1] for x in s):
            return False, "s values must be in {-1, 0, 1}"

        expected_vec = np.array(self.phi_map(tuple(s)))
        actual_vec = np.array(vec)

        if not np.allclose(actual_vec, expected_vec, atol=atol):
            diff = np.linalg.norm(actual_vec - expected_vec)
            return False, f"vec mismatch (diff={diff:.6f})"

        if abs(np.linalg.norm(actual_vec) - 1.0) > unit_norm_tol:
            return False, f"vec not unit vector (norm={np.linalg.norm(actual_vec):.6f})"

        if packet.get('act') not in ("query", "store", "align", "verify"):
            return False, f"invalid act: {packet.get('act')}"

        return True, "ok"

    def compute_hmac(self, packet: Dict, secret: str) -> str:
        """計算 HMAC-SHA256（使用 canonical JSON）"""
        payload = {
            "id": packet.get("id"),
            "t": packet.get("t"),
            "s": packet.get("s"),
            "vec": packet.get("vec"),
            "act": packet.get("act"),
            "control": packet.get("control", {}),
            "lang": packet.get("lang")
        }
        # 移除 None 值，避免序列化差異
        payload = {k: v for k, v in payload.items() if v is not None}

        msg = self.canonical_json(payload)
        digest = hmac.new(secret.encode('utf-8'), msg, hashlib.sha256).hexdigest()
        return f"hmac-sha256:{digest}"

    def verify_hmac(self, packet: Dict, secret: str, sig: str) -> Tuple[bool, str]:
        """驗證 HMAC（fail-open）"""
        if sig == "none":
            return True, "no signature (fail-open)"
        if not sig.startswith("hmac-sha256:"):
            return True, f"unknown sig format (fail-open): {sig[:30]}..."

        expected = self.compute_hmac(packet, secret)
        if sig == expected:
            return True, "signature valid"
        return False, "signature mismatch"

    @staticmethod
    def generate_test_packet(triple: Tuple[int, int, int],
                             act: str = "query",
                             eps: float = 0.55,
                             origin: Optional[str] = None) -> Dict:
        """生成標準測試封包"""
        vec = TSPv01.phi_map(triple)
        pkt = {
            "tsp": "0.1",
            "id": f"test-{triple}-{int(time.time())}",
            "t": int(time.time()),
            "act": act,
            "s": list(triple),
            "vec": vec,
            "control": {"eps": eps, "profile": "sta-v0.1"},
            "lang": {"src": "zh-tw", "tgt": "en"},
            "sig": "none"
        }
        if origin:
            pkt["origin"] = origin
        return pkt


